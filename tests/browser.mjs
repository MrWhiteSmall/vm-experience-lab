import { chromium, expect } from '@playwright/test';
import { writeFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const errors = [];
const external = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:5196') && !request.url().startsWith('blob:http://127.0.0.1:5196') && !request.url().startsWith('data:')) external.push(request.url()); });
const results = [];
const record = (name, extra = {}) => { results.push({ name, passed: true, ...extra }); console.log('PASS', name, extra); };

try {
  await page.goto('http://127.0.0.1:5196/', { waitUntil: 'networkidle' });
  await expect(page.locator('.disc-button')).toHaveCount(8);
  assert(await page.evaluate(() => document.querySelector('.room').getBoundingClientRect().width === innerWidth), 'The experience room must fill the browser width');
  await page.screenshot({ path: 'artifacts/desk.png', fullPage: true });
  await page.locator('[data-start="kolibri"]').hover();
  await expect(page.locator('#discovery-card')).toBeVisible();
  await expect(page.locator('#discovery-card')).toContainText('探索小任务');
  await page.screenshot({ path: 'artifacts/disc-card.png', fullPage: true });
  await page.locator('[data-filter="china"]').click();
  await expect(page.locator('.disc-button')).toHaveCount(2);
  await page.locator('[data-start="deepin"]').click();
  await expect(page.locator('#details-dialog')).toBeVisible();
  await expect(page.locator('#details-start')).toBeDisabled();
  await expect(page.locator('#details-content')).toContainText('尚不能');
  await page.locator('#details-dialog .dialog-close').click();
  await page.locator('[data-filter="all"]').click();
  await page.locator('[data-start="haiku"]').focus();
  await expect(page.locator('#discovery-card')).toContainText('Haiku');
  record('分类、悬停卡片、键盘聚焦与未接入状态');

  const started = Date.now();
  await page.locator('[data-start="kolibri"]').click();
  await page.waitForFunction(() => window.vmLab.phase === 'running', undefined, { timeout: 60000 });
  await page.waitForFunction(() => { const c = document.querySelector('#vm-screen canvas'); return c.style.display === 'block' && c.width >= 640; }, undefined, { timeout: 45000 });
  await page.waitForTimeout(8000);
  const kolibri = await page.evaluate(() => ({ instructions: window.vmLab.emulator.get_instruction_counter(), width: document.querySelector('#vm-screen canvas').width, height: document.querySelector('#vm-screen canvas').height }));
  assert(kolibri.instructions > 1000000);
  const screenBox = await page.locator('#screen').boundingBox();
  const roomBox = await page.locator('.room').boundingBox();
  const toolbarBox = await page.locator('#session-toolbar').boundingBox();
  assert(screenBox.y > toolbarBox.y + toolbarBox.height, 'Focused screen must remain below the toolbar');
  assert(screenBox.y + screenBox.height < roomBox.y + roomBox.height, 'Focused screen must fit inside the room');
  const largeCanvasBox = await page.locator('#vm-screen canvas').boundingBox();
  assert(largeCanvasBox.width > 1000, 'The focused guest display must be large enough to read at desktop size');
  await page.screenshot({ path: 'artifacts/kolibri-boot.png', fullPage: true });
  await page.locator('#pause-button').click();
  await page.waitForFunction(() => window.vmLab.phase === 'paused');
  const stoppedCount = await page.evaluate(() => window.vmLab.emulator.get_instruction_counter());
  await page.waitForTimeout(350);
  assert.equal(await page.evaluate(() => window.vmLab.emulator.get_instruction_counter()), stoppedCount);
  await page.locator('#pause-button').click();
  await page.waitForFunction(previous => window.vmLab.emulator.get_instruction_counter() !== previous, stoppedCount);
  record('KolibriOS 真实引导、图形桌面、暂停及恢复', { elapsed_ms: Date.now() - started, ...kolibri });

  const canvas = page.locator('#vm-screen canvas');
  const canvasBox = await canvas.boundingBox();
  await page.mouse.click(canvasBox.x + canvasBox.width * .017, canvasBox.y + canvasBox.height * .986);
  await page.waitForTimeout(1000);
  const adapters = await page.evaluate(() => ({ keyboard: Boolean(window.vmLab.emulator.keyboard_adapter?.emu_enabled), mouse: Boolean(window.vmLab.emulator.mouse_adapter?.emu_enabled) }));
  assert(adapters.keyboard && adapters.mouse, 'Both actual browser input adapters must be enabled');
  await page.mouse.move(canvasBox.x + canvasBox.width * .3, canvasBox.y + canvasBox.height * .8);
  await page.mouse.move(canvasBox.x + canvasBox.width * .017, canvasBox.y + canvasBox.height * .986, { steps: 5 });
  await page.mouse.down();
  await page.mouse.up();
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'artifacts/kolibri-interaction.png', fullPage: true });
  record('屏幕点击启用实际键盘与鼠标适配器', adapters);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Tab');
  await page.waitForFunction(() => !document.pointerLockElement);
  await page.locator('#back-button').click();
  await page.locator('[data-start="tinycore"]').click();
  await expect(page.locator('#details-dialog')).toBeVisible();
  await expect(page.locator('.details-running-warning')).toBeVisible();
  await page.locator('#details-start').click();
  await page.waitForFunction(() => window.vmLab.disc === 'tinycore' && window.vmLab.phase === 'running', undefined, { timeout: 60000 });
  await page.waitForFunction(() => { const c = document.querySelector('#vm-screen canvas'); return c.style.display === 'block' && c.width >= 640; }, undefined, { timeout: 90000 });
  await page.waitForTimeout(4000);
  await page.screenshot({ path: 'artifacts/tinycore-boot.png', fullPage: true });
  record('跨系统换盘与 Tiny Core 真实图形引导', await page.evaluate(() => ({ instructions: window.vmLab.emulator.get_instruction_counter(), width: document.querySelector('#vm-screen canvas').width, height: document.querySelector('#vm-screen canvas').height })));
  await page.locator('#screen').click();
  await page.mouse.move(1050, 800, { steps: 30 });
  await page.waitForTimeout(500);
  const readPixels = () => page.evaluate(() => {
    const canvas = document.querySelector('#vm-screen canvas');
    return Array.from(canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data);
  });
  const difference = (a, b) => a.reduce((count, value, index) => count + (value !== b[index] ? 1 : 0), 0);
  const desktopPixels = await readPixels();
  await page.mouse.down({ button: 'right' });
  await page.mouse.up({ button: 'right' });
  await page.waitForTimeout(700);
  const menuPixels = await readPixels();
  const menuDifference = difference(desktopPixels, menuPixels);
  assert(menuDifference > 1000, 'A real guest menu must appear after the mouse click');
  assert(await page.evaluate(() => window.vmLab.emulator.keyboard_adapter.emu_enabled && window.vmLab.emulator.mouse_adapter.emu_enabled), 'Captured clicks must preserve both input adapters');
  await page.screenshot({ path: 'artifacts/tinycore-interaction.png', fullPage: true });
  await page.keyboard.press('Escape');
  await page.waitForTimeout(700);
  const closedPixels = await readPixels();
  assert(difference(desktopPixels, closedPixels) < menuDifference / 4, 'Browser keyboard Escape must dismiss the actual guest menu');
  record('Tiny Core 鼠标打开真实菜单、键盘关闭菜单及持续输入', { changed_channels: menuDifference });
  await page.keyboard.press('Escape');
  await page.keyboard.press('Tab');
  await page.waitForFunction(() => !document.pointerLockElement);
  await page.locator('#eject-button').click();
  await page.waitForFunction(() => window.vmLab.phase === 'idle' && !window.vmLab.emulator);
  await expect(page.locator('#idle-screen')).toBeVisible();
  record('弹出光盘后释放模拟器并回到桌面');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(800);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page must not overflow horizontally');
  await page.screenshot({ path: 'artifacts/mobile-desk.png', fullPage: true });
  await page.locator('#desk-focus-button').click();
  await page.waitForTimeout(600);
  const mobileScreenBox = await page.locator('#screen').boundingBox();
  assert(mobileScreenBox.width > 330 && mobileScreenBox.x >= 0 && mobileScreenBox.x + mobileScreenBox.width <= 390, 'The mobile display should use available width without clipping');
  await page.screenshot({ path: 'artifacts/mobile-large-screen.png', fullPage: true });
  await page.locator('#back-button').click();
  await page.locator('[data-info="deepin"]').click();
  await expect(page.locator('#details-dialog')).toBeVisible();
  await page.screenshot({ path: 'artifacts/mobile-details.png', fullPage: true });
  await page.locator('#details-dialog .dialog-close').click();
  record('手机布局、介绍入口和无横向溢出');
  assert.deepEqual(errors, [], 'No uncaught browser errors');
  assert.deepEqual(external, [], 'Runtime must not depend on external network requests');
  record('无浏览器异常，运行时资源全部本地加载');
  await writeFile('artifacts/browser-results.json', JSON.stringify({ checked_at: new Date().toISOString(), results, errors, external_requests: external }, null, 2));
} catch (error) {
  await page.screenshot({ path: 'artifacts/failure.png', fullPage: true }).catch(() => {});
  await writeFile('artifacts/browser-results.json', JSON.stringify({ results, errors, external_requests: external, failure: String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
